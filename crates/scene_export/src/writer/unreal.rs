//! Writes an Unreal Engine import script beside the meshes.
//!
//! Unreal 5 reads glTF through its Interchange importer and ships with Python
//! scripting, so the Unreal target keeps the `.glb` meshes the level build already
//! makes and generates one Python script with the placement baked in: run it from
//! **Tools → Execute Python Script** (or the Python console) inside the project, and
//! it imports every mesh under `/Game/<level>` and spawns a `StaticMeshActor` per
//! solid at its place in the open level.
//!
//! Axes and units: the level is in Godot's frame (right-handed, Y up, metres); Unreal
//! is left-handed, Z up, centimetres. The script converts each translation as
//! `(x_ue, y_ue, z_ue) = (z_g, -x_g, y_g) * 100` -- undoing the Godot swizzle back to
//! the map's own axes and negating the map's Y for the handedness -- and converts the
//! full orientation by a change of basis. The meshes themselves arrive through the glTF
//! importer, which does its own Y-up-to-Z-up conversion. Matching this placement
//! frame against a specific Interchange importer/version still requires a native
//! engine check; the mathematical tests verify the stated frame, not the importer.

use crate::level::Level;

/// How the Unreal script is generated.
#[derive(Debug, Clone)]
pub struct UnrealOptions {
    /// The content path the meshes are imported under, e.g. `/Game/arena`.
    pub content_dir: String,
}

impl UnrealOptions {
    /// Options for a level of the given name: content under `/Game/<name>`.
    pub fn for_level(name: &str) -> Self {
        UnrealOptions {
            content_dir: format!("/Game/{name}"),
        }
    }
}

/// Builds the Python import script, every placement baked in.
pub fn write(level: &Level, options: &UnrealOptions) -> String {
    let mut entries = String::new();
    let mut setup = String::new();
    for (index, entity) in level.entities.iter().enumerate() {
        setup.push_str(&format!("    actors[{index}].set_editor_property(\"tags\", [\"heron_brush_entity_index:{index}\"])\n"));
        if let Some(light) = super::common_entities::light(entity) {
            let [r,g,b,a] = light.color;
            setup.push_str(&format!("    light = actors[{index}].get_component_by_class(unreal.LightComponent)\n    light.set_light_color(unreal.LinearColor({r:.6},{g:.6},{b:.6},{a:.6}), False)\n    light.set_intensity({:.6})\n    light.set_editor_property(\"cast_shadows\", {})\n", light.energy, if light.shadows { "True" } else { "False" }));
            if light.kind != "Directional" {
                setup.push_str(&format!("    light.set_editor_property(\"attenuation_radius\", {:.6})\n", light.range * 100.));
            }
            if light.kind == "Spot" {
                setup.push_str(&format!("    light.set_editor_property(\"outer_cone_angle\", {:.6})\n", light.half_angle));
            }
        }
        let t = &entity.transform;
        // Godot frame back to the map's axes: map = (g.z, g.x, g.y); Unreal
        // then negates the map's Y for its handedness, and speaks centimetres.
        let (gx, gy, gz) = (t.translation[0], t.translation[1], t.translation[2]);
        let (ux, uy, uz) = (gz * 100.0, -gx * 100.0, gy * 100.0);
        // Native lights and player starts look along +X, while the source
        // convention looks along -Z, which this basis maps to -X.
        let native = entity.mesh.is_none() && matches!(entity.classname.as_str(), "light" | "light_spot" | "light_sun" | "info_player_start" | "info_player_deathmatch");
        let [qx, qy, qz, qw] = unreal_rotation(t.rotation_yxz, native).to_array();
        let [sx, sy, sz] = [t.scale[2], t.scale[0], t.scale[1]];
        entries.push_str(&format!(
            "    (\"{name}\", \"{classname}\", {mesh}, ({ux:.6}, {uy:.6}, {uz:.6}), ({qx:.9}, {qy:.9}, {qz:.9}, {qw:.9}), ({sx:.6}, {sy:.6}, {sz:.6})),\n",
            name = escape(&entity.name),
            classname = escape(&entity.classname),
            mesh = match &entity.mesh {
                Some(path) => format!("\"{}\"", escape(path)),
                None => "None".to_string(),
            },
        ));
    }

    format!(
        r#""""Generated by Heron Brush. Run inside the Unreal editor:
Tools -> Execute Python Script, pointing at this file, with the exported folder
kept next to it. Imports the meshes under {content} and spawns the level's
actors into the open level."""

import os
import json
import unreal

HERE = os.path.dirname(os.path.abspath(__file__))
CONTENT = "{content}"
ENTITY_DATA = json.loads("{metadata}")

ENTRIES = [
{entries}]


def import_mesh(relative):
    task = unreal.AssetImportTask()
    task.filename = os.path.join(HERE, relative)
    task.destination_path = CONTENT
    task.automated = True
    task.save = True
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
    stem = os.path.splitext(os.path.basename(relative))[0]
    return unreal.EditorAssetLibrary.load_asset(f"{{CONTENT}}/{{stem}}")


def build():
    # EditorLevelLibrary is deprecated since UE 5.0; the actor subsystem is its replacement.
    world = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    actors = []
    native = {{"light": unreal.PointLight, "light_spot": unreal.SpotLight,
              "light_sun": unreal.DirectionalLight, "info_player_start": unreal.PlayerStart,
              "info_player_deathmatch": unreal.PlayerStart}}
    for name, classname, mesh, position, quaternion, scale in ENTRIES:
        location = unreal.Vector(position[0], position[1], position[2])
        rotation = unreal.Quat(*quaternion).rotator()
        if mesh is None:
            actor = world.spawn_actor_from_class(native.get(classname, unreal.Actor), location, rotation)
            actor.set_actor_scale3d(unreal.Vector(*scale))
            actors.append(actor)
            actor.set_actor_label(f"{{classname}}:{{name}}")
            continue
        asset = import_mesh(mesh)
        if asset is None:
            unreal.log_warning(f"Heron Brush: could not import {{mesh}}")
            actor = world.spawn_actor_from_class(unreal.Actor, location, rotation)
            actor.set_actor_label(name)
            actor.set_actor_scale3d(unreal.Vector(*scale))
            actors.append(actor)
            continue
        actor = world.spawn_actor_from_object(asset, location, rotation)
        actor.set_actor_scale3d(unreal.Vector(*scale))
        actors.append(actor)
        actor.set_actor_label(name)
{setup}


build()
"#,
        content = escape(&options.content_dir),
        metadata = escape(&level.to_json()),
        entries = entries,
        setup = setup,
    )
}

/// Change the complete source orientation into the writer's (z, -x, y)
/// frame. For the reflection C, R_ue = C * R_source * C^-1; quaternion
/// vector components transform as det(C) * C * q.xyz, while w is unchanged.
/// Native +X-facing actors need a LOCAL half turn, not a world yaw offset.
/// Unreal's Quat.rotator performs its own Euler convention conversion:
/// https://dev.epicgames.com/documentation/en-us/unreal-engine/python-api/class/Quat
fn unreal_rotation([pitch, yaw, roll]: [f64; 3], native: bool) -> glam::DQuat {
    let q = glam::DQuat::from_euler(glam::EulerRot::YXZ, yaw, pitch, roll);
    let converted = glam::DQuat::from_xyzw(-q.z, q.x, -q.y, q.w);
    if native {
        converted * glam::DQuat::from_rotation_z(std::f64::consts::PI)
    } else {
        converted
    }
}

/// Escapes a string for a Python string literal.
fn escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n").replace('\r', "\\r").replace('\t', "\\t")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::level::{Entity, Transform};

    fn a_level() -> Level {
        Level {
            format: 1,
            generator: "test".into(),
            name: "arena".into(),
            scale: 32.0,
            textures: Vec::new(),
            entities: vec![Entity {
                name: "worldspawn".into(),
                classname: "worldspawn".into(),
                group: Vec::new(),
                transform: Transform {
                    // Godot frame (x, y, z) = (map.y, map.z, map.x).
                    translation: [2.0, 3.0, 1.0],
                    ..Transform::default()
                },
                solid: true,
                mesh: Some("arena/worldspawn.glb".into()),
                surfaces: Vec::new(),
                collision: None,
                properties: Default::default(),
                targets: Vec::new(),
                scene: None,
                tags: Vec::new(),
            }],
        }
    }

    #[test]
    fn the_script_converts_to_unreal_axes_and_centimetres() {
        let script = write(&a_level(), &UnrealOptions::for_level("arena"));
        // map = (1, 2, 3) -> unreal (x, -y, z) * 100 = (100, -200, 300).
        assert!(script.contains("(100.000000, -200.000000, 300.000000)"), "{script}");
        assert!(script.contains("/Game/arena"));
        assert!(script.contains("arena/worldspawn.glb"));
    }

    #[test]
    fn complete_orientation_and_scale_preserve_transformed_points() {
        use glam::{DMat3, DQuat, DVec3};
        let mut level = a_level();
        level.entities[0].transform.rotation_yxz = [0.37, -1.12, 0.64];
        level.entities[0].transform.scale = [2.0, 0.7, 3.1];
        let t = &level.entities[0].transform;
        let script = write(&level, &UnrealOptions::for_level("arena"));
        let entry = script.lines().find(|l| l.trim_start().starts_with("(\"worldspawn\"")).unwrap();
        let values: Vec<Vec<f64>> = entry.split('(').skip(2).map(|part|
            part.split(')').next().unwrap().split(',').map(|n| n.trim().parse().unwrap()).collect()
        ).collect();
        let position = DVec3::new(values[0][0], values[0][1], values[0][2]);
        let q = DQuat::from_xyzw(values[1][0],values[1][1],values[1][2],values[1][3]);
        let scale = DVec3::new(values[2][0],values[2][1],values[2][2]);
        let [x,y,z] = t.rotation_yxz;
        let basis = crate::scene::basis_from_euler_yxz(crate::math::Vec3::new(x,y,z));
        let source = DMat3::from_cols_array(&basis).transpose();
        let convert = |p: DVec3| DVec3::new(p.z,-p.x,p.y);
        for point in [DVec3::X,DVec3::Y,DVec3::Z,DVec3::new(0.3,-2.,4.)] {
            let expected = convert(source * (DVec3::from_array(t.scale) * point) + DVec3::from_array(t.translation)) * 100.;
            let actual = q * (scale * convert(point) * 100.) + position;
            assert!((actual - expected).length() < 1e-5, "{actual} != {expected}");
        }
        assert!(script.contains("rotation = unreal.Quat(*quaternion).rotator()"));
        assert_eq!(script.matches("actor.set_actor_scale3d(unreal.Vector(*scale))").count(),3);
        let native = unreal_rotation(t.rotation_yxz, true);
        assert!((native * DVec3::X - convert(source * -DVec3::Z)).length() < 1e-10);
        assert!((native * DVec3::Z - convert(source * DVec3::Y)).length() < 1e-10);
    }

}
