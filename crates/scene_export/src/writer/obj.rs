//! Wavefront OBJ writer.
//!
//! Godot imports one surface per `o` block, which is what lets the `.tscn`
//! point at entity meshes by path. Triangles go out counter-clockwise and V is
//! measured from the bottom; the importer undoes both.

use crate::geometry::Mesh;
use crate::scene::format_float;
use std::collections::HashMap;
use std::fmt::Write as _;
use std::hash::{BuildHasherDefault, Hasher};

#[derive(Debug, Clone, Copy)]
pub struct ObjOptions {
    /// Write triangles clockwise instead. Only needed if a Godot version stops
    /// reversing the winding at import.
    pub flip_faces: bool,
    /// Write V as-is instead of measuring it from the bottom.
    pub flip_uv_v: bool,
}

impl Default for ObjOptions {
    fn default() -> Self {
        ObjOptions {
            flip_faces: false,
            flip_uv_v: true,
        }
    }
}

/// A hash for keys that are already numbers. The default one is built to
/// survive hostile input; these are rounded coordinates out of a map file, and
/// looking them up was the biggest thing this writer did.
#[derive(Default)]
struct NumberHash(u64);

impl Hasher for NumberHash {
    fn finish(&self) -> u64 {
        self.0
    }

    fn write(&mut self, bytes: &[u8]) {
        let mut h = self.0;
        for chunk in bytes.chunks(8) {
            let mut packed = 0u64;
            for (i, b) in chunk.iter().enumerate() {
                packed |= (*b as u64) << (i * 8);
            }
            h = (h ^ packed).wrapping_mul(0x9E37_79B9_7F4A_7C15);
            h ^= h >> 31;
        }
        self.0 = h;
    }
}

/// Deduplicates a float triple stream and hands back 1-based OBJ indices.
struct Stream {
    keys: HashMap<[u64; 3], u32, BuildHasherDefault<NumberHash>>,
    text: String,
    count: u32,
}

impl Stream {
    fn with_room(room: usize) -> Self {
        Stream {
            keys: HashMap::with_capacity_and_hasher(room, BuildHasherDefault::default()),
            text: String::new(),
            count: 0,
        }
    }

    fn intern(&mut self, prefix: &str, values: &[f64]) -> u32 {
        let mut key = [0u64; 3];
        for (i, v) in values.iter().enumerate().take(3) {
            key[i] = ((v * 1e6).round() as i64) as u64;
        }
        if let Some(id) = self.keys.get(&key) {
            return *id;
        }
        self.count += 1;
        let _ = write!(self.text, "{prefix}");
        for v in values {
            let _ = write!(self.text, " {}", format_float(*v));
        }
        self.text.push('\n');
        self.keys.insert(key, self.count);
        self.count
    }
}

pub fn write(mesh: &Mesh, source_name: &str, options: ObjOptions) -> String {
    // Sized up front: a mesh of a quarter million triangles would otherwise
    // grow and rehash these a dozen times on the way.
    let room: usize = mesh.surfaces.iter().map(|s| s.vertices.len()).sum();
    let mut positions = Stream::with_room(room);
    let mut uvs = Stream::with_room(room);
    let mut normals = Stream::with_room(room);
    let mut faces = String::new();

    for surface in &mesh.surfaces {
        if surface.indices.is_empty() {
            continue;
        }
        // The surface name doubles as the object name, so the surface order in
        // the imported mesh matches `mesh.surfaces`.
        let _ = writeln!(faces, "o {}", sanitize(&surface.texture));
        let _ = writeln!(faces, "usemtl {}", sanitize(&surface.texture));

        let mut refs: Vec<(u32, u32, u32)> = Vec::with_capacity(surface.vertices.len());
        for v in &surface.vertices {
            let p = positions.intern("v", &[v.position.x, v.position.y, v.position.z]);
            let uv_v = if options.flip_uv_v {
                1.0 - v.uv.y
            } else {
                v.uv.y
            };
            let t = uvs.intern("vt", &[v.uv.x, uv_v]);
            let n = normals.intern("vn", &[v.normal.x, v.normal.y, v.normal.z]);
            refs.push((p, t, n));
        }

        for tri in surface.indices.chunks(3) {
            if tri.len() < 3 {
                continue;
            }
            let order = if options.flip_faces {
                [0usize, 1, 2]
            } else {
                [0usize, 2, 1]
            };
            faces.push('f');
            for slot in order {
                let (p, t, n) = refs[tri[slot] as usize];
                let _ = write!(faces, " {p}/{t}/{n}");
            }
            faces.push('\n');
        }
    }

    let mut out = String::with_capacity(positions.text.len() + uvs.text.len() + faces.len() + 256);
    let _ = writeln!(out, "# generated by heron_brush from {source_name}");
    let _ = writeln!(
        out,
        "# {} surfaces, {} triangles",
        mesh.surfaces.len(),
        mesh.triangle_count()
    );
    out.push_str(&positions.text);
    out.push_str(&uvs.text);
    out.push_str(&normals.text);
    out.push_str(&faces);
    out
}

/// OBJ names cannot hold whitespace, and Godot uses them as surface names.
fn sanitize(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| if c.is_whitespace() { '_' } else { c })
        .collect();
    if cleaned.is_empty() {
        "surface".to_string()
    } else {
        cleaned
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::geometry::{Surface, Vertex};
    use crate::math::{Vec2, Vec3};

    fn quad() -> Mesh {
        let vertices = vec![
            Vertex {
                position: Vec3::new(0.0, 0.0, 0.0),
                normal: Vec3::Y,
                uv: Vec2::new(0.0, 0.0),
            },
            Vertex {
                position: Vec3::new(1.0, 0.0, 0.0),
                normal: Vec3::Y,
                uv: Vec2::new(1.0, 0.0),
            },
            Vertex {
                position: Vec3::new(1.0, 0.0, 1.0),
                normal: Vec3::Y,
                uv: Vec2::new(1.0, 1.0),
            },
        ];
        Mesh {
            surfaces: vec![Surface {
                texture: "stone floor".into(),
                vertices,
                indices: vec![0, 1, 2],
            }],
        }
    }

    #[test]
    fn writes_one_object_per_surface_with_reversed_winding() {
        let text = write(&quad(), "t.map", ObjOptions::default());
        assert!(text.contains("o stone_floor"));
        assert!(text.contains("usemtl stone_floor"));
        // Written 0, 2, 1 so the importer's own reversal lands back on 0, 1, 2.
        assert!(text.contains("f 1/1/1 3/3/1 2/2/1"), "faces were:\n{text}");
    }

    #[test]
    fn v_is_measured_from_the_bottom() {
        let text = write(&quad(), "t.map", ObjOptions::default());
        assert!(text.contains("vt 0.0 1.0"), "uvs were:\n{text}");
        assert!(text.contains("vt 1.0 0.0"));
    }

    #[test]
    fn repeated_positions_are_written_once() {
        let mut mesh = quad();
        let extra = mesh.surfaces[0].vertices[0];
        mesh.surfaces[0].vertices.push(extra);
        mesh.surfaces[0].indices.extend_from_slice(&[0, 1, 3]);
        let text = write(&mesh, "t.map", ObjOptions::default());
        assert_eq!(text.lines().filter(|l| l.starts_with("v ")).count(), 3);
    }
}
