#!/usr/bin/env python3
"""Refresh the portable motion lab resource list after exporting the map."""
from pathlib import Path
base=Path(__file__).resolve().parent
root=base.parents[1]
files=[base/name for name in ('README.md','build.py','motion_lab.fgd','preview.png')]
files.extend(p for p in (base/'godot').rglob('*') if p.is_file() and '.godot' not in p.parts and p.suffix!='.uid' and p.name!='verification.json')
lines=['// Generated by demos/motion_lab/bundle.py.','pub const FILES: &[(&str, &[u8])] = &[']
for p in sorted(files):
    lines.append(f'    ("motion_lab/{p.relative_to(base).as_posix()}", include_bytes!("../../../{p.relative_to(root).as_posix()}")),')
lines.append('];')
(root/'crates/editor_core/src/motion_sample_resources.rs').write_text('\n'.join(lines)+'\n')
print(f'Bundled {len(files)} support files')
